/** Create immutable copies of the bundled source fonts and their shared catalog. */
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSourceData } from '../../shared/source/data';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const SOURCES = resolve(ROOT, 'fonts/sources');
const MANIFEST = resolve(SOURCES, 'manifest.json');
const CATALOG = resolve(ROOT, 'shared/source/catalog.ts');
const sha256 = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');

type Manifest = {
  version: 1;
  current: Record<string, string>;
  revisions: Record<string, { fontId: string }>;
};

function object(value: unknown, at: string): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) throw Error(`${at}: expected an object`);
  return Object.fromEntries(Object.entries(value));
}

function fontId(value: unknown, at: string): string {
  if (typeof value !== 'string' || !value.trim()) throw Error(`${at}: expected a font ID`);
  return value;
}

function digest(value: unknown, at: string): string {
  if (typeof value !== 'string' || !/^[0-9a-f]{64}$/.test(value)) throw Error(`${at}: expected a SHA256 digest`);
  return value;
}

function parseManifest(value: unknown): Manifest {
  const data = object(value, 'manifest');
  if (data.version !== 1) throw Error('manifest: unsupported version');
  const revisions: Manifest['revisions'] = {};
  for (const [key, value] of Object.entries(object(data.revisions, 'manifest.revisions'))) {
    revisions[digest(key, 'revision key')] = { fontId: fontId(object(value, key).fontId, `${key}.fontId`) };
  }
  const current: Manifest['current'] = {};
  for (const [id, value] of Object.entries(object(data.current, 'manifest.current'))) {
    const hash = digest(value, id);
    if (revisions[hash]?.fontId !== id) throw Error(`manifest: current ${id} has no matching revision`);
    current[fontId(id, 'current font ID')] = hash;
  }
  return { version: 1, current, revisions };
}

async function optionalFile(path: string): Promise<Buffer | undefined> {
  try { return await readFile(path); }
  catch (error: unknown) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return undefined;
    throw error;
  }
}

const sorted = <T>(record: Record<string, T>) => Object.fromEntries(Object.entries(record).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));

function catalog(manifest: Manifest): string {
  const sources = Object.entries(manifest.revisions).map(([digest, { fontId }]) => ({ kind: 'outline-v1', digest, fontId }));
  return `// Generated by tools/authored/build-sources.ts. Older source revisions remain available.\n`
    + `import type { SourceRef } from './model';\n\n`
    + `export const SOURCE_REVISIONS: readonly SourceRef[] = ${JSON.stringify(sources, null, 2)};\n\n`
    + `const CURRENT: Readonly<Record<string, string>> = ${JSON.stringify(manifest.current, null, 2)};\n\n`
    + `export function sourceForFont(fontId: string): SourceRef | null {\n`
    + `  const digest = CURRENT[fontId];\n`
    + `  return SOURCE_REVISIONS.find(source => source.digest === digest) ?? null;\n`
    + `}\n`;
}

async function main() {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check')) throw Error('Usage: node --import tsx tools/authored/build-sources.ts [--check]');
  const check = args.includes('--check');
  const oldBytes = await optionalFile(MANIFEST);
  const previous = oldBytes ? parseManifest(JSON.parse(oldBytes.toString('utf8'))) : { version: 1, current: {}, revisions: {} } satisfies Manifest;
  const current: Manifest['current'] = {};
  const revisions: Manifest['revisions'] = { ...previous.revisions };
  const snapshots = new Map<string, Buffer>();

  for (const name of (await readdir(resolve(ROOT, 'fonts'))).filter(name => name.endsWith('.json')).sort()) {
    const bytes = await readFile(resolve(ROOT, 'fonts', name));
    const input: unknown = JSON.parse(bytes.toString('utf8'));
    const id = parseSourceData(input, name).id;
    if (id in current) throw Error(`Duplicate source font ID: ${id}`);
    const hash = sha256(bytes);
    if (revisions[hash] && revisions[hash].fontId !== id) throw Error(`Source digest ${hash} belongs to another font`);
    current[id] = hash;
    revisions[hash] = { fontId: id };
    snapshots.set(hash, bytes);
  }

  const missing: string[] = [];
  for (const [hash, revision] of Object.entries(revisions)) {
    const path = resolve(SOURCES, `${hash}.json`);
    const existing = await optionalFile(path);
    if (existing) {
      if (sha256(existing) !== hash) throw Error(`Immutable source was modified: ${path}`);
      const input: unknown = JSON.parse(existing.toString('utf8'));
      if (parseSourceData(input, path).id !== revision.fontId) throw Error(`Source identity differs from its manifest: ${path}`);
    } else {
      const bytes = snapshots.get(hash);
      if (!bytes) throw Error(`Historical source is missing and cannot be regenerated: ${path}`);
      if (check) missing.push(path);
      else {
        await mkdir(SOURCES, { recursive: true });
        await writeFile(path, bytes, { flag: 'wx' });
      }
    }
  }

  const manifest: Manifest = { version: 1, current: sorted(current), revisions: sorted(revisions) };
  const outputs = [
    [MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`],
    [CATALOG, catalog(manifest)],
  ];
  for (const [path, expected] of outputs) {
    const existing = await optionalFile(path);
    if (existing?.toString('utf8') === expected) continue;
    if (check) missing.push(path);
    else {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, expected);
    }
  }
  if (missing.length) throw Error(`Source catalog is out of date. Run tools/authored/build-sources.ts.\n${missing.join('\n')}`);
  process.stdout.write(`${JSON.stringify({ mode: check ? 'check' : 'build', currentFonts: Object.keys(current).length, sourceRevisions: Object.keys(revisions).length })}\n`);
}

main().catch((error: unknown) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
